def _ingest(tmp_path: Path, source: Path):
    """Ingest the reused provenance PDF through the current production API."""
    runtime = StorageRuntime.from_config(StorageConfig.built_in(root=tmp_path / "runtime"))
    registry = SourceAssetRegistry.load(runtime=runtime)
    storage = StorageClient(LocalStorageBackend(tmp_path / "artifacts")).for_shared_data()
    context = ExecutionContext(
        run_id="run-canonical",
        correlation_id="cor-canonical",
        principal_id="fixture-test",
    )
    result = IngestService(storage, extractor=PyPdfExtractor(), registry=registry).ingest(
        source, context=context, registry=registry
    )
    return result, storage


def test_canonical_document_still_preserves_current_python_ingest_shape(
    tmp_path: Path, provenance_pdf: Path
) -> None:
    """Verify the existing Python ingest path still returns the v2 document shape."""
    result, storage = _ingest(tmp_path, provenance_pdf)
    payload = json.loads(storage.open(result.provenance_key).read())
    assert result.document.document_id.startswith("pdf-")
    assert payload["document_id"] == result.document.document_id
    assert payload["parser"]["selected"] == "basic"
    assert payload["pages"]
    assert all(
        page["physical_page_index"] == i
        for i, page in enumerate(payload["pages"])
    )


def test_expected_canonical_content_fixture_matches_contract(v3_2_fixture_root: Path) -> None:
    """Assert the frozen v3.2 canonical fixture stores text once per node."""
    content = json.loads(
        (v3_2_fixture_root / "expected" / "canonical_content.json").read_text(
            encoding="utf-8"
        )
    )
    assert content["schema"] == "cognityx.ingest.canonical-content/v3.2"
    texts = [node["content"]["text"] for node in content["content_nodes"]]
    assert texts
    assert len(texts) == len(set(texts))
    assert all(node["source_selectors"] for node in content["content_nodes"])


def test_frozen_canonical_projection_loads_into_complete_records(
    frozen_canonical_artifact: CanonicalContentArtifact,
    v3_2_fixture_root: Path,
) -> None:
    """Match every authoritative fixture resource, node, text, hash, and selector."""
    expected = json.loads(
        (v3_2_fixture_root / "expected" / "canonical_content.json").read_text(
            encoding="utf-8"
        )
    )
    actual_resources = {
        item.resource_id: item for item in frozen_canonical_artifact.resources
    }
    assert frozen_canonical_artifact.schema == expected["schema"]
    assert {
        item["resource_id"]: item["source_sha256"] for item in expected["resources"]
    } == {
        identifier: item.source_sha256
        for identifier, item in actual_resources.items()
    }
    actual_nodes = {
        item.node_id: item for item in frozen_canonical_artifact.content_nodes
    }
    for expected_node in expected["content_nodes"]:
        actual = actual_nodes[expected_node["node_id"]]
        assert actual.resource_id == expected_node["resource_id"]
        assert actual.owner_division_id == expected_node["owner_division_id"]
        assert actual.node_kind == expected_node["node_kind"]
        assert actual.content.text == expected_node["content"]["text"]
        assert actual.content.sha256 == expected_node["content"]["sha256"]
        assert actual.source_selectors[0].source_path == expected_node[
            "source_selectors"
        ][0]["source_path"]
        assert actual.source_selectors[0].char_start == expected_node[
            "source_selectors"
        ][0]["char_start"]
        assert actual.source_selectors[0].char_end == expected_node[
            "source_selectors"
        ][0]["char_end"]


def test_frozen_selectors_reproduce_exact_source_substrings(
    frozen_canonical_artifact: CanonicalContentArtifact,
    v3_2_fixture_root: Path,
) -> None:
    """Use only real frozen ranges to recover every exact authoritative text."""
    for node in frozen_canonical_artifact.content_nodes:
        selector = node.source_selectors[0]
        assert selector.source_path is not None
        assert selector.char_start is not None
        assert selector.char_end is not None
        source = (v3_2_fixture_root / selector.source_path).read_text(
            encoding="utf-8"
        )
        assert source[selector.char_start : selector.char_end] == node.content.text


def test_every_content_node_hashes_exact_utf8_bytes(
    frozen_canonical_artifact: CanonicalContentArtifact,
) -> None:
    """Verify hashes from exact Unicode bytes without normalization or decoding loss."""
    for node in frozen_canonical_artifact.content_nodes:
        assert node.content.sha256 == hashlib.sha256(
            node.content.text.encode("utf-8")
        ).hexdigest()



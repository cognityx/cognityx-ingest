def test_every_node_has_one_deepest_direct_owner(
    frozen_canonical_artifact: CanonicalContentArtifact,
) -> None:
    """Prove each node appears in exactly its declared direct Division list."""
    direct_owners: dict[str, list[str]] = {}
    for division in frozen_canonical_artifact.divisions:
        for node_id in division.direct_node_ids:
            direct_owners.setdefault(node_id, []).append(division.division_id)
    assert set(direct_owners) == {
        item.node_id for item in frozen_canonical_artifact.content_nodes
    }
    assert all(
        owners == [
            next(
                node.owner_division_id
                for node in frozen_canonical_artifact.content_nodes
                if node.node_id == node_id
            )
        ]
        for node_id, owners in direct_owners.items()
    )


def test_direct_and_subtree_lookup_return_existing_nodes_in_source_order(
    frozen_canonical_artifact: CanonicalContentArtifact,
) -> None:
    """Reconstruct parent content through references without parent text storage."""
    direct = frozen_canonical_artifact.direct_nodes("div-policy-root")
    subtree = frozen_canonical_artifact.subtree_nodes("div-policy-root")
    assert [item.node_id for item in direct] == ["pol-heading-root"]
    assert [item.node_id for item in subtree] == [
        "pol-heading-root",
        "pol-heading-42",
        "pol-p1",
        "pol-p2",
        "pol-p3",
        "pol-p4",
        "pol-heading-71",
        "pol-p5",
    ]
